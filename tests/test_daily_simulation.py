def test_conservation_of_totals(dataset):
    """Totals are bound to the world model (docs/MODEL_SPEC.md §1/§2, W1 mass-balance fix).

    Values changed with the fix: the status quo no longer counts the first reading of each
    container (775.7 t of pre-window glass) and both sides are generated by the same world
    r_c = Σlevel/ΣΔt instead of the biased walk-forward estimate (+ phantom reset mass).
    """
    readings, locations, cfg = dataset

    hist_df = build_historical_daily(readings, locations, cfg)
    opt_df = simulate_optimized_daily(readings, locations, cfg, seed=42)

    # Historical: 11,701 readings − 1,338 first readings (boundary start) = 10,363 emptyings,
    # collecting exactly the measured in-window glass (readings 2…n): 6,943.5 t
    assert hist_df["n_emptyings"].sum() == 11701 - 1338
    assert 6940.0 <= hist_df["tonnage_t"].sum() <= 6947.0

    # Simulated: cannot collect more than the world produces in the window (7,613.9 t)
    produced = simulate_daily.produced_total(readings, cfg)
    assert 7610.0 <= produced <= 7618.0
    assert 6900.0 <= opt_df["tonnage_t"].sum() <= produced


def test_efficiency_and_overflow_reduction(dataset):
    """Truthful replay: the timer policy cuts overfull emptyings and overflow days.

    Before the W1 fix this test asserted avg fill >= 80 % and > status quo; that was an artefact
    of truth == belief (the simulation emptied exactly at its own estimate). Against the fixed
    world the walk-forward estimate is biased high (+15.5 %), so the policy empties early:
    avg true fill at emptying 65.3 % vs 67.0 % status quo (uncapped model fill).
    """
    readings, locations, cfg = dataset

    hist_df = build_historical_daily(readings, locations, cfg)
    opt_df = simulate_optimized_daily(readings, locations, cfg, seed=42)

    h_avg_fill = (
        hist_df["avg_fill_at_emptying_pct"] * hist_df["n_emptyings"]
    ).sum() / hist_df["n_emptyings"].sum()
    o_avg_fill = (
        opt_df["avg_fill_at_emptying_pct"] * opt_df["n_emptyings"]
    ).sum() / opt_df["n_emptyings"].sum()

    assert 60.0 <= o_avg_fill <= 70.0
    assert 60.0 <= h_avg_fill <= 70.0

    # Overfull emptyings (true fill >= 110 % at the visit) drop sharply vs the status quo
    h_overfull = hist_df["n_containers_overfull_at_visit"].sum()
    o_overfull = opt_df["n_containers_overfull_at_visit"].sum()
    assert o_overfull < 0.25 * h_overfull

    # Overflow container-days (true fill >= 110 %) drop by > 90 %
    h_days = simulate_daily.mass_ledger(hist_df)["overflow_container_days"]
    o_days = simulate_daily.mass_ledger(opt_df)["overflow_container_days"]
    assert o_days == opt_df["n_overflows_simulated"].sum()
    assert o_days < 0.1 * h_days
